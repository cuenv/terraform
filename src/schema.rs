fn cue_label(name: &str) -> Result<String> {
    Ok(serde_json::to_string(name)?)
}

fn nullable(value: &str) -> String {
    format!("({value} | null)")
}

fn push_field(
    fields: &mut Vec<String>,
    names: &mut HashMap<String, String>,
    name: &str,
    schema_path: &str,
    required: bool,
    value: &str,
) -> Result<()> {
    let cue_name = camel_case(name, false)
        .with_context(|| format!("convert Terraform field {name:?} in {schema_path}"))?;
    register_name(names, &cue_name, name, &format!("fields in {schema_path}"))?;
    let marker = if required { "!" } else { "?" };
    fields.push(format!(
        "{}{marker}: {value} {}",
        cue_label(&cue_name)?,
        terraform_attribute(name)?
    ));
    Ok(())
}

fn bool_field(object: &serde_json::Map<String, Value>, name: &str) -> Result<Option<bool>> {
    match object.get(name) {
        None | Some(Value::Null) => Ok(None),
        Some(value) => value
            .as_bool()
            .map(Some)
            .with_context(|| format!("Terraform schema field {name:?} must be boolean")),
    }
}

fn string_field<'a>(
    object: &'a serde_json::Map<String, Value>,
    name: &str,
) -> Result<Option<&'a str>> {
    match object.get(name) {
        None | Some(Value::Null) => Ok(None),
        Some(value) => value
            .as_str()
            .map(Some)
            .with_context(|| format!("Terraform schema field {name:?} must be a string")),
    }
}

fn bound(value: Option<&Value>, default: usize, name: &str) -> Result<usize> {
    match value {
        None | Some(Value::Null) => Ok(default),
        Some(value) => value
            .as_u64()
            .and_then(|number| usize::try_from(number).ok())
            .with_context(|| {
                format!("Terraform schema field {name:?} must be a non-negative integer")
            }),
    }
}

fn optional_bound(value: Option<&Value>, name: &str) -> Result<Option<usize>> {
    match value {
        None | Some(Value::Null) => Ok(None),
        Some(value) => bound(Some(value), 0, name).map(Some),
    }
}

fn as_object(name: &'static str) -> impl FnOnce(&Value) -> Result<&serde_json::Map<String, Value>> {
    move |value| {
        value
            .as_object()
            .with_context(|| format!("Terraform schema field {name:?} must be an object"))
    }
}
